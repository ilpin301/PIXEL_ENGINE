#pragma once
// Resource manager (docs/architecture/03 section 4.4). An asset is either a blob in ROM (zero-copy) or a file in the Storage.
// The asset blob header and its parsers are in pge/asset.h.
#include <stdint.h>
#include "pge/error.h"
#include "pge/memory.h"
#include "pge/storage.h"

namespace pge {

typedef uint16_t AssetId;  // index into the game's const AssetEntry table (generated by tools/ in S5.4)
enum class AssetType : uint8_t { Sprites, Tileset, Font, Sound, Pattern, Blob, Tilemap, Strings };

struct AssetInfo {
  AssetType type;
  uint32_t size;
  bool in_rom;
};

// rom != nullptr: the blob lives in flash/ROM; otherwise it is a file at `path` in the Storage.
struct AssetEntry {
  AssetType type;
  const void* rom;
  uint32_t size;
  const char* path;
};

class Resources {
 public:
  void init(const AssetEntry* table, uint16_t count, Storage* storage);  // storage may be nullptr (ROM only)
  Error info(AssetId id, AssetInfo& out) const;                          // InvalidArg for id >= count
  const void* rom(AssetId id) const;  // zero-copy pointer, nullptr if storage-backed or bad id
  // ROM: copy. Storage: readFile. cap < size -> OutOfMemory; file length != size -> Corrupt;
  // storage-backed without Storage -> NotSupported; bad id or null dst with size > 0 -> InvalidArg.
  Error load(AssetId id, void* dst, uint32_t cap, uint32_t& len);
  // ROM: *out = the ROM pointer (no copy, no arena use). Storage: size bytes (align 8) from the init arena `a`, then load.
  // An arena failure (e.g. locked after the first tick) gives OutOfMemory.
  Error loadPersistent(Arena& a, AssetId id, const void** out);

 private:
  const AssetEntry* table_ = nullptr;
  uint16_t count_ = 0;
  Storage* storage_ = nullptr;
};

}  // namespace pge
